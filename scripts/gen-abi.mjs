// Regenerates the typed ABI used by the dashboard and the agents from the forge artifact.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
const art = JSON.parse(readFileSync("contracts/out/FalaVault.sol/FalaVault.json", "utf8"));
const body = `// Generated by scripts/gen-abi.mjs — do not edit.\nexport const falaVaultAbi = ${JSON.stringify(art.abi)} as const;\n`;
for (const out of ["src/lib/abi.ts", "agents/src/lib/abi.ts"]) {
  mkdirSync(out.replace(/\/[^/]+$/, ""), { recursive: true });
  writeFileSync(out, body);
}
console.log("abi written");
